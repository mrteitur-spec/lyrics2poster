from __future__ import annotations

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


def _font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    candidates = []
    if bold:
        candidates += ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf"]
    else:
        candidates += ["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf"]
    for path in candidates:
        if Path(path).exists():
            try:
                return ImageFont.truetype(path, size=size)
            except OSError:
                pass
    return ImageFont.load_default()


def _fit_font(draw: ImageDraw.ImageDraw, text: str, max_width: int, start: int, min_size: int = 28):
    for size in range(start, min_size - 1, -2):
        font = _font(size, bold=True)
        if draw.textbbox((0, 0), text, font=font)[2] <= max_width:
            return font
    return _font(min_size, bold=True)


def add_title_overlay(image: Image.Image, *, title: str, artist: str, style: str) -> Image.Image:
    poster = image.convert("RGBA")
    draw = ImageDraw.Draw(poster, "RGBA")
    width, height = poster.size
    margin = int(width * 0.085)

    # Small framing label is generated by the app, not part of the lyrics.
    label_font = _font(max(18, width // 42), bold=True)
    draw.text((margin, int(height * 0.72)), "SONG POSTER STUDIO", font=label_font, fill=(255, 255, 255, 210))
    draw.line((margin, int(height * 0.755), width - margin, int(height * 0.755)), fill=(255, 255, 255, 150), width=2)

    clean_title = " ".join((title or "Untitled").split())[:120]
    clean_artist = " ".join((artist or "Unknown artist").split())[:120]
    title_font = _fit_font(draw, clean_title, width - margin * 2, start=width // 11, min_size=30)
    artist_font = _font(max(24, width // 24), bold=False)

    # Wrap long titles into at most two lines.
    words = clean_title.split()
    lines, current = [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if draw.textbbox((0, 0), candidate, font=title_font)[2] <= width - margin * 2:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    lines = lines[:2]

    y = int(height * 0.785)
    for line in lines:
        draw.text((margin, y), line, font=title_font, fill=(255, 255, 255, 255), stroke_width=1, stroke_fill=(0, 0, 0, 100))
        y += int(title_font.size * 1.08)
    y += int(height * 0.018)
    draw.text((margin, y), clean_artist, font=artist_font, fill=(255, 255, 255, 225))
    return poster.convert("RGB")
